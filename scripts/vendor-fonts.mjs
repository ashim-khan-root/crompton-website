#!/usr/bin/env node
/**
 * Vendor the three web fonts into the repo and generate src/styles/fonts.css.
 *
 * The site previously loaded them with a CSS `@import` from fonts.googleapis.com,
 * which is a render-blocking request to a third party before first paint, plus two
 * preconnects. This script downloads the same files Google serves, keeps only the
 * subsets the site can actually need, and writes local @font-face rules.
 *
 * The unicode-range values are copied verbatim from Google's own CSS — they are
 * not guessed here, because a wrong range silently stops glyphs from loading.
 *
 *   node scripts/vendor-fonts.mjs          download + write
 *   node scripts/vendor-fonts.mjs --check  verify the files on disk match
 *
 * Re-run this only if a family or weight range changes. The output is committed,
 * so a fresh clone builds without network access.
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const FONT_DIR = path.join(ROOT, 'public', 'fonts');
const CSS_OUT = path.join(ROOT, 'src', 'styles', 'fonts.css');

// A current desktop UA is what makes Google return woff2 variable fonts.
// An old UA returns .ttf per weight, which is roughly 4x the bytes.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const FAMILIES = [
  // slug,        google family,        weight axis,    subsets kept
  { slug: 'inter', family: 'Inter', axis: 'wght@300..700', subsets: ['latin', 'latin-ext'] },
  { slug: 'plus-jakarta-sans', family: 'Plus Jakarta Sans', axis: 'wght@400..800', subsets: ['latin', 'latin-ext'] },
  { slug: 'noto-sans-arabic', family: 'Noto Sans Arabic', axis: 'wght@300..700', subsets: ['arabic', 'latin', 'latin-ext'] },
];

const checkOnly = process.argv.includes('--check');

function cssUrl({ family, axis }) {
  return `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:${axis}&display=swap`;
}

/** Split Google's CSS into [{ subset, block }] on the `/* subset *\/` markers. */
function splitBlocks(css) {
  const out = [];
  const re = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/gi;
  let m;
  while ((m = re.exec(css)) !== null) out.push({ subset: m[1], block: m[2] });
  return out;
}

async function fetchFamily(spec) {
  const res = await fetch(cssUrl(spec), { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${spec.family}: CSS fetch failed (${res.status})`);
  return splitBlocks(await res.text());
}

async function download(url, dest) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`download failed (${res.status}): ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(dest, buf);
  return buf.length;
}

const problems = [];
const lines = [
  '/* GENERATED by scripts/vendor-fonts.mjs — do not edit by hand.',
  ' * Re-run the script to refresh. Files live in public/fonts/. */',
  '',
];
let total = 0;

for (const spec of FAMILIES) {
  const blocks = await fetchFamily(spec);
  const kept = blocks.filter((b) => spec.subsets.includes(b.subset));

  if (kept.length !== spec.subsets.length) {
    const got = kept.map((b) => b.subset).join(', ');
    problems.push(`${spec.family}: expected subsets [${spec.subsets}] got [${got}]`);
  }

  for (const { subset, block } of kept) {
    const url = block.match(/url\((https:[^)]+)\)/)?.[1];
    if (!url) {
      problems.push(`${spec.family}/${subset}: no url in block`);
      continue;
    }
    const file = `${spec.slug}-${subset}.woff2`;
    const dest = path.join(FONT_DIR, file);

    if (checkOnly) {
      if (!existsSync(dest)) problems.push(`missing: public/fonts/${file}`);
      else total += (await readFile(dest)).length;
    } else {
      await mkdir(FONT_DIR, { recursive: true });
      total += await download(url, dest);
    }

    // Rewrite only the src, keep weight/style/display/unicode-range as Google wrote them.
    lines.push(block.replace(/url\(https:[^)]+\)/, `url('/fonts/${file}')`), '');
  }
}

if (!checkOnly) {
  await writeFile(CSS_OUT, lines.join('\n'));
}

if (checkOnly) {
  const onDisk = existsSync(FONT_DIR) ? (await readdir(FONT_DIR)).filter((f) => f.endsWith('.woff2')) : [];
  console.log(`checked ${onDisk.length} font files, ${(total / 1024).toFixed(1)} KiB referenced`);
} else {
  console.log(`wrote ${lines.filter((l) => l.startsWith('@font-face')).length} @font-face rules → src/styles/fonts.css`);
  console.log(`downloaded ${(total / 1024).toFixed(1)} KiB into public/fonts/`);
}

if (problems.length) {
  console.error('\nPROBLEMS:');
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}
